export function buildAvailabilityFixtures(referenceDate = new Date()): readonly AvailabilitySlot[] {
  return slotTemplates.map((template) => {
    const startsAt = new Date(referenceDate);
    startsAt.setUTCHours(template.startHourUtc, template.startMinute, 0, 0);
    startsAt.setUTCDate(startsAt.getUTCDate() + template.dayOffset);

    const endsAt = new Date(startsAt.getTime() + template.durationMinutes * 60_000);
    return {
      id: template.id,
      providerId: template.providerId,
      clinicId: template.clinicId,
      visitMode: template.visitMode,
      startsAt: startsAt.toISOString(),
      endsAt: endsAt.toISOString(),
      timezone: 'Asia/Dubai',
      status: 'available',
    };
  });
}
